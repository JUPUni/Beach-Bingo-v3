/**
 * BEACH ADVENTURE — free-to-play level map (the casual, non-wagering mode).
 *
 * Each level: 1–4 cards, a target pattern and a ball budget. Balls are called on a timer;
 * the player daubs called numbers and must shout BINGO before the balls run out.
 * Stars reward a fast bingo; coins buy boosters. Win rates per level (for a perfect dauber)
 * are verified by simulation in the test-suite so the difficulty curve stays sane.
 */
