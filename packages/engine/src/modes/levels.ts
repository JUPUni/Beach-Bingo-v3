export type LevelStatus = 'playing' | 'won' | 'lost';

export interface LevelRun {
  level: LevelDef;
  cards: BingoCard[];
  lookups: Int8Array[];
  playable: number[];
  /** Player daubs per card (free spaces pre-daubed). */
  daubs: number[];
  drum: number[];
  drawnCount: number;
  extraBalls: number;
  autoDaub: boolean;
  doubleCoins: boolean;
  status: LevelStatus;
  score: number;
  /** Balls remaining when BINGO was claimed. */
  ballsLeftAtBingo: number;
  /** Balls called when BINGO was claimed. */
  ballAtBingo: number;
  winningCard: number;
  falseClaims: number;
}

export function startLevel(level: LevelDef, rng: Rng, opts: { autoDaub?: boolean; doubleCoins?: boolean } = {}): LevelRun {
  const cards = range(1, level.cards).map(() => generateCard('75', rng));
  return {
    level,
    cards,
    lookups: cards.map(cellLookup),
    playable: cards.map(playableMask),
    daubs: cards.map(freeMask),
    drum: sample(range(1, 75), 75, rng),
    drawnCount: 0,
    extraBalls: 0,
    autoDaub: Boolean(opts.autoDaub),
    doubleCoins: Boolean(opts.doubleCoins),
    status: 'playing',
    score: 0,
    ballsLeftAtBingo: 0,
    ballAtBingo: 0,
    winningCard: -1,
    falseClaims: 0,
  };
}

export function ballBudget(run: LevelRun): number {
  return Math.min(75, run.level.maxBalls + run.extraBalls);
}

export function ballsLeft(run: LevelRun): number {
  return ballBudget(run) - run.drawnCount;
}

export function calledBalls(run: LevelRun): number[] {
  return run.drum.slice(0, run.drawnCount);
}

export const DAUB_POINTS = 50;
export const SPEED_POINTS = 50;
export const BINGO_POINTS = 1000;
export const BALL_LEFT_POINTS = 100;

/** Call the next ball (or null when the budget is spent). */
export function callBall(run: LevelRun): number | null {
  if (run.status !== 'playing' || ballsLeft(run) <= 0) return null;
  const ball = run.drum[run.drawnCount++]!;
  if (run.autoDaub) {
    run.lookups.forEach((lookup, i) => {
      const cell = lookup[ball] ?? -1;
      if (cell >= 0 && !(run.daubs[i]! & (1 << cell))) {
        run.daubs[i]! |= 1 << cell;
        run.score += DAUB_POINTS;
      }
    });
  }
  return ball;
}

/** Player taps a square. Only called numbers can be daubed; returns whether it counted. */
export function daub(run: LevelRun, cardIndex: number, cell: number, reactionMs?: number): boolean {
  if (run.status !== 'playing') return false;
  const card = run.cards[cardIndex];
  if (!card || cell < 0 || cell >= card.cells.length) return false;
  if (run.daubs[cardIndex]! & (1 << cell)) return false;
  const value = card.cells[cell]!;
  if (value <= 0 || !run.drum.slice(0, run.drawnCount).includes(value)) return false;
  run.daubs[cardIndex]! |= 1 << cell;
  const speed = reactionMs === undefined ? 0 : Math.max(0, 1 - reactionMs / run.level.callMs);
  run.score += DAUB_POINTS + Math.round(SPEED_POINTS * speed);
  return true;
}

/** Crab Pinch booster: daub any square. */
export function crabPinch(run: LevelRun, cardIndex: number, cell: number): boolean {
  if (run.status !== 'playing') return false;
  const card = run.cards[cardIndex];
  if (!card || card.cells[cell] === undefined || card.cells[cell]! <= 0) return false;
  if (run.daubs[cardIndex]! & (1 << cell)) return false;
  run.daubs[cardIndex]! |= 1 << cell;
  return true;
}

export function addBalls(run: LevelRun, count: number): void {
  run.extraBalls += count;
  if (run.status === 'lost') run.status = 'playing';
}

/** Cards whose *daubed* squares complete the level pattern. */
export function bingoCards(run: LevelRun): number[] {
  const pattern = PATTERNS_75[run.level.pattern];
  return run.daubs.flatMap((d, i) => (isComplete(d, pattern, run.playable[i]!) ? [i] : []));
}

export function winningShape(run: LevelRun, cardIndex: number): number[] {
  return winningCells(run.daubs[cardIndex]!, PATTERNS_75[run.level.pattern], run.playable[cardIndex]!);
}

export function claimBingo(run: LevelRun): boolean {
  if (run.status !== 'playing') return false;
  const winners = bingoCards(run);
  if (!winners.length) {
    run.falseClaims++;
    run.score = Math.max(0, run.score - 200);
    return false;
  }
  run.status = 'won';
  run.winningCard = winners[0]!;
  run.ballsLeftAtBingo = ballsLeft(run);
  run.ballAtBingo = run.drawnCount;
  run.score += BINGO_POINTS + run.ballsLeftAtBingo * BALL_LEFT_POINTS;
  return true;
}

/** Mark the run lost once the budget is spent (the UI gives a short grace period first). */
export function outOfBalls(run: LevelRun): boolean {
  if (run.status === 'playing' && ballsLeft(run) <= 0) run.status = 'lost';
  return run.status === 'lost';
}

/** 3★ / 2★ for a bingo claimed by the level's star thresholds, else 1★. */
export function starsFor(run: LevelRun): 0 | 1 | 2 | 3 {
  if (run.status !== 'won') return 0;
  const [three, two] = run.level.stars;
  return run.ballAtBingo <= three ? 3 : run.ballAtBingo <= two ? 2 : 1;
}

export function coinsFor(run: LevelRun): number {
  return run.level.reward * starsFor(run) * (run.doubleCoins ? 2 : 1);
}

/** Probability a perfect player (auto-daub, instant claim) beats the level — Monte Carlo. */
export function levelWinRate(level: LevelDef, rng: Rng, trials: number): number {
  let wins = 0;
  for (let t = 0; t < trials; t++) {
    const run = startLevel(level, rng, { autoDaub: true });
    while (run.status === 'playing' && callBall(run) !== null) {
      if (bingoCards(run).length) claimBingo(run);
    }
    if (run.status === 'won') wins++;
  }
  return wins / trials;
}
